from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Dict, Any


@dataclass
class CPGInput:
    """
    Sensory feedback passed from the musculoskeletal physics model (MuJoCo)
    into the spiking neural network (CPG).
    - Cutaneous (CUT) afferents from plantar paw contact sensors.
    - Muscle spindle primary (Ia) afferents: derived from muscle length and stretch velocity.
    - Golgi tendon organ (Ib) afferents: derived from muscle activation and tendon tension/force.
    - Phase state: stance vs. swing.
    - Joint angles for tracking.
    """
    # Cutaneous touch (Hz)
    cut_L: float = 0.0
    cut_R: float = 0.0

    # Ia afferents Left limb (length in m, velocity in m/s, firing rate in Hz)
    ia_len_E_L: float = 0.0
    ia_vel_E_L: float = 0.0
    ia_rate_E_L: float = 0.0
    ia_len_F_L: float = 0.0
    ia_vel_F_L: float = 0.0
    ia_rate_F_L: float = 0.0

    # Ia afferents Right limb
    ia_len_E_R: float = 0.0
    ia_vel_E_R: float = 0.0
    ia_rate_E_R: float = 0.0
    ia_len_F_R: float = 0.0
    ia_vel_F_R: float = 0.0
    ia_rate_F_R: float = 0.0

    # Ib afferents Left limb (muscle activation, tendon force in N, firing rate in Hz)
    ib_act_E_L: float = 0.0
    ib_force_E_L: float = 0.0
    ib_rate_E_L: float = 0.0
    ib_act_F_L: float = 0.0
    ib_force_F_L: float = 0.0
    ib_rate_F_L: float = 0.0

    # Ib afferents Right limb
    ib_act_E_R: float = 0.0
    ib_force_E_R: float = 0.0
    ib_rate_E_R: float = 0.0
    ib_act_F_R: float = 0.0
    ib_force_F_R: float = 0.0
    ib_rate_F_R: float = 0.0

    # Locomotion phase ("stance" or "swing")
    phase_L: str = "stance"
    phase_R: str = "swing"

    # Kinematic joint angles (rad)
    ankle_angle_m_L: float = 0.0
    ankle_angle_ref_L: float = 0.0
    knee_angle_m_L: float = 0.0
    hip_angle_m_L: float = 0.0


@dataclass
class CPGOutput:
    """
    Motor commands generated by the CPG sent to MuJoCo muscle actuators.
    """
    mus_E_L: float = 0.0
    mus_F_L: float = 0.0
    mus_E_R: float = 0.0
    mus_F_R: float = 0.0
    t_ms: float = 0.0
    extra: Dict[str, Any] = field(default_factory=dict)


class CPGAdapter(ABC):
    @abstractmethod
    def update(self, cpg_in: CPGInput):
        """Updates sensory input generators in the CPG."""
        pass

    @abstractmethod
    def step(self) -> CPGOutput:
        """Simulates CPG for dt and returns muscle drives."""
        pass

    @abstractmethod
    def build_cpg(self):
        """Builds neuronal populations and connections."""
        pass

    @abstractmethod
    def get_logs(self) -> Dict[str, Any]:
        """Returns recorded spike and membrane potential data."""
        pass